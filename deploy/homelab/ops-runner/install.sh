#!/usr/bin/env bash
# Installs (or re-installs) the ops runner as a systemd --user service on the
# homelab. Idempotent. Run ON the homelab:
#
#   bash ~/discord-bot/deploy/homelab/ops-runner/install.sh
#
# What it does:
#   1. makes sure OPS_RUNNER_SECRET exists in .env.homelab (generates one if not)
#   2. links the unit into ~/.config/systemd/user and enables it
#   3. checks lingering is on, so the service survives logout
#
# The bot reads OPS_RUNNER_SECRET at start, so if step 1 generated a new one
# the bot needs recreating once for the runner to authenticate:
#   cd ~/discord-bot/deploy/homelab && docker compose -p discord-bot --env-file ./.env.homelab up -d --no-build bot
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEPLOY_DIR="$(dirname "$HERE")"
ENV_FILE="$DEPLOY_DIR/.env.homelab"
UNIT_NAME="discord-bot-ops-runner.service"
UNIT_DIR="$HOME/.config/systemd/user"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "no $ENV_FILE - deploy the bot first" >&2
  exit 1
fi

# 1. secret
if grep -q '^OPS_RUNNER_SECRET=.\+' "$ENV_FILE"; then
  echo "OPS_RUNNER_SECRET already set"
  SECRET_ADDED=0
else
  SECRET="$(openssl rand -hex 32)"
  # Strip any blank placeholder line first so there is exactly one.
  sed -i '/^OPS_RUNNER_SECRET=$/d' "$ENV_FILE"
  printf '\n# Shared secret for deploy/homelab/ops-runner (generated by install.sh)\nOPS_RUNNER_SECRET=%s\n' "$SECRET" >> "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "OPS_RUNNER_SECRET generated and written to .env.homelab"
  SECRET_ADDED=1
fi

# 2. unit
mkdir -p "$UNIT_DIR"
cp "$HERE/ops-runner.service" "$UNIT_DIR/$UNIT_NAME"
systemctl --user daemon-reload
systemctl --user enable --now "$UNIT_NAME"
systemctl --user restart "$UNIT_NAME"
echo "$UNIT_NAME enabled and running"

# 3. linger
if loginctl show-user "$USER" -p Linger 2>/dev/null | grep -q 'Linger=yes'; then
  echo "lingering is on - the runner survives logout"
else
  echo "WARNING: lingering is off for $USER. The runner stops when you log out. Fix with:" >&2
  echo "  sudo loginctl enable-linger $USER" >&2
fi

if [[ "$SECRET_ADDED" == "1" ]]; then
  cat <<MSG

The bot has not seen the new secret yet. Recreate it once:
  cd $DEPLOY_DIR && docker compose -p discord-bot --env-file ./.env.homelab up -d --no-build bot
MSG
fi

echo
echo "Follow it with:  journalctl --user -u $UNIT_NAME -f"
